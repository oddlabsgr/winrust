//! Winrust Base pixel font: glyphs up to 4×5, drawn into `text.bmp`'s 5×6 cells and used
//! for labels. Original design; letters are capitals only (the LCD shows text in capitals).

pub struct Glyph {
    pub width: u32,
    pub rows: [&'static str; 5],
}

const fn g(rows: [&'static str; 5]) -> Glyph {
    let mut width = 0;
    let mut i = 0;
    while i < 5 {
        if rows[i].len() > width {
            width = rows[i].len();
        }
        i += 1;
    }
    Glyph {
        width: width as u32,
        rows,
    }
}

pub fn glyph(c: char) -> Glyph {
    match c.to_ascii_uppercase() {
        'A' => g([".##.", "#..#", "####", "#..#", "#..#"]),
        'B' => g(["###.", "#..#", "###.", "#..#", "###."]),
        'C' => g([".###", "#...", "#...", "#...", ".###"]),
        'D' => g(["###.", "#..#", "#..#", "#..#", "###."]),
        'E' => g(["####", "#...", "###.", "#...", "####"]),
        'F' => g(["####", "#...", "###.", "#...", "#..."]),
        'G' => g([".###", "#...", "#.##", "#..#", ".###"]),
        'H' => g(["#..#", "#..#", "####", "#..#", "#..#"]),
        'I' => g(["###", ".#.", ".#.", ".#.", "###"]),
        'J' => g(["..##", "...#", "...#", "#..#", ".##."]),
        'K' => g(["#..#", "#.#.", "##..", "#.#.", "#..#"]),
        'L' => g(["#...", "#...", "#...", "#...", "####"]),
        'M' => g(["#..#", "####", "####", "#..#", "#..#"]),
        'N' => g(["#..#", "##.#", "#.##", "#..#", "#..#"]),
        'O' => g([".##.", "#..#", "#..#", "#..#", ".##."]),
        'P' => g(["###.", "#..#", "###.", "#...", "#..."]),
        'Q' => g([".##.", "#..#", "#..#", "#.#.", ".#.#"]),
        'R' => g(["###.", "#..#", "###.", "#.#.", "#..#"]),
        'S' => g([".###", "#...", ".##.", "...#", "###."]),
        'T' => g(["###", ".#.", ".#.", ".#.", ".#."]),
        'U' => g(["#..#", "#..#", "#..#", "#..#", ".##."]),
        'V' => g(["#.#", "#.#", "#.#", "#.#", ".#."]),
        'W' => g(["#..#", "#..#", "####", "####", "#..#"]),
        'X' => g(["#..#", "#..#", ".##.", "#..#", "#..#"]),
        'Y' => g(["#.#", "#.#", ".#.", ".#.", ".#."]),
        'Z' => g(["####", "...#", ".##.", "#...", "####"]),
        '0' => g(["####", "#..#", "#..#", "#..#", "####"]),
        '1' => g([".#.", "##.", ".#.", ".#.", "###"]),
        '2' => g(["###.", "...#", ".##.", "#...", "####"]),
        '3' => g(["###.", "...#", ".##.", "...#", "###."]),
        '4' => g(["#..#", "#..#", "####", "...#", "...#"]),
        '5' => g(["####", "#...", "###.", "...#", "###."]),
        '6' => g([".##.", "#...", "###.", "#..#", ".##."]),
        '7' => g(["####", "...#", "..#.", ".#..", ".#.."]),
        '8' => g([".##.", "#..#", ".##.", "#..#", ".##."]),
        '9' => g([".##.", "#..#", ".###", "...#", ".##."]),
        '"' => g(["#.#", "#.#", "...", "...", "..."]),
        '@' => g([".##.", "#.##", "#.##", "#...", ".###"]),
        '…' => g(["....", "....", "....", "....", "#.#."]),
        '.' => g([".", ".", ".", ".", "#"]),
        ':' => g([".", "#", ".", "#", "."]),
        '(' => g([".#", "#.", "#.", "#.", ".#"]),
        ')' => g(["#.", ".#", ".#", ".#", "#."]),
        '-' => g(["...", "...", "###", "...", "..."]),
        '\'' => g(["#", "#", ".", ".", "."]),
        '!' => g(["#", "#", "#", ".", "#"]),
        '_' => g(["....", "....", "....", "....", "####"]),
        '+' => g(["...", ".#.", "###", ".#.", "..."]),
        '\\' => g(["#...", ".#..", ".#..", "..#.", "...#"]),
        '/' => g(["...#", "..#.", ".#..", ".#..", "#..."]),
        '[' | '<' | '{' => g(["##", "#.", "#.", "#.", "##"]),
        ']' | '>' | '}' => g(["##", ".#", ".#", ".#", "##"]),
        '^' => g([".#.", "#.#", "...", "...", "..."]),
        '&' => g([".#..", "#.#.", ".#..", "#.##", ".#.#"]),
        '%' => g(["#..#", "..#.", ".#..", "#...", "#..#"]),
        ',' => g(["..", "..", "..", ".#", "#."]),
        '=' => g(["...", "###", "...", "###", "..."]),
        '$' => g([".###", "##..", ".##.", "..##", "###."]),
        '#' => g(["#.#.", "####", "#.#.", "####", "#.#."]),
        'Å' => g(["..#.", ".##.", "#..#", "####", "#..#"]),
        'Ö' => g(["#..#", ".##.", "#..#", "#..#", ".##."]),
        'Ä' => g(["#..#", ".##.", "#..#", "####", "#..#"]),
        '?' => g(["###.", "...#", ".##.", "....", ".#.."]),
        '*' => g(["....", "#.#.", ".#..", "#.#.", "...."]),
        _ => g(["...", "...", "...", "...", "..."]),
    }
}
